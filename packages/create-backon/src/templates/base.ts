export function renderPackageJson(projectName: string, db: Answers["db"]): string {
  const dependencies: Record<string, string> = {
    "@mednours/backon": "latest",
    hono: "^4.6.14",
    zod: "^3.24.1",
    ...dbDependencies(db),
  };

  const pkg = {
    name: projectName,
    version: "0.1.0",
    private: true,
    type: "module",
    scripts: {
      dev: "bun run --watch index.ts",
      start: "bun run index.ts",
      test: "bun test",
      typecheck: "tsc --noEmit",
    },
    dependencies,
    devDependencies: {
      "@types/bun": "latest",
      typescript: "^5.7.2",
    },
  };

  return `${JSON.stringify(pkg, null, 2)}\n`;
}

export function renderReadme(answers: Answers): string {
  const routeList = answers.routes.length
    ? answers.routes.map((route) => `- \`src/endpoints/${route}/\``).join("\n")
    : "- (none yet — add one under src/endpoints/)";

  return `# ${answers.projectName}

Generated by \`create-backon\`.

## Getting started

\`\`\`
bun install
cp .env.example .env   # fill in real values
bun run dev
\`\`\`

## Database: ${answers.db}

${dbReadmeNote(answers.db)}

## Routes

${routeList}

Each route folder follows the same shape: \`*.routes.ts\` wires HTTP methods
to controller functions, \`*.controller.ts\` validates the request (via
\`defineRoute\` from \`@mednours/backon\`) and calls into \`*.services.ts\`,
which is where real data access belongs.
`;
}
