import { afterEach, describe, expect, it } from "bun:test";
import { mkdtemp, rm, readFile, access } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { addRoute } from "../src/add-route";
import { addMethod } from "../src/add-method";
import { addCrudMethods } from "../src/crud-scaffold";
import { generateProject } from "../src/generate";

const cleanupDirs: string[] = [];

afterEach(async () => {
  while (cleanupDirs.length) {
    const dir = cleanupDirs.pop();
    if (dir) await rm(dir, { recursive: true, force: true });
  }
});

async function makeTmpDir(): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "create-backon-generate-client-test-"));
  cleanupDirs.push(dir);
  return dir;
}

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

/** Actually runs the generated scripts/generate-client.<ext> as a real subprocess — the only way to test what it writes, since its logic lives entirely inside the generated string, not as importable functions. */
async function runGenerateClient(root: string, ext: "ts" | "js"): Promise<{ stdout: string; exitCode: number }> {
  const proc = Bun.spawn(["bun", "run", `scripts/generate-client.${ext}`], { cwd: root, stdout: "pipe", stderr: "pipe" });
  const exitCode = await proc.exited;
  const stdout = await new Response(proc.stdout).text();
  const stderr = await new Response(proc.stderr).text();
  if (exitCode !== 0) throw new Error(`generate-client exited ${exitCode}\n${stdout}\n${stderr}`);
  return { stdout, exitCode };
}

describe("generate-client script (TypeScript)", () => {
  it("writes a typed client with one function per method, grouped by endpoint", async () => {
    const cwd = await makeTmpDir();
    const { root } = await generateProject(
      { projectName: ".", framework: "hono", language: "typescript", db: "none", routes: [], copyEnv: false },
      cwd
    );
    await addRoute("users", root);
    await addCrudMethods("users", root);
    await addRoute("orders", root);
    await addMethod("orders", { verb: "get", path: "/", name: "list", needsBody: false, needsQuery: true }, root);

    await runGenerateClient(root, "ts");

    const outPath = join(root, "client/api.ts");
    expect(await exists(outPath)).toBe(true);
    const contents = await readFile(outPath, "utf-8");

    expect(contents).toContain("Auto-generated by `bun run generate-client`");
    expect(contents).toContain('import type { createBodySchema, updateBodySchema } from "../src/endpoints/users/users.controller";');
    expect(contents).toContain('import type { listQuerySchema } from "../src/endpoints/orders/orders.controller";');
    expect(contents).toContain("export const usersApi = {");
    expect(contents).toContain('list: <T = unknown>() => request<T>("/users"),');
    expect(contents).toContain('create: <T = unknown>(body: z.infer<typeof createBodySchema>) => request<T>("/users", { method: "POST", body: JSON.stringify(body) }),');
    expect(contents).toContain('getById: <T = unknown>(id: string) => request<T>("/users/" + id),');
    expect(contents).toContain('update: <T = unknown>(id: string, body: z.infer<typeof updateBodySchema>) => request<T>("/users/" + id, { method: "PUT", body: JSON.stringify(body) }),');
    expect(contents).toContain('remove: <T = unknown>(id: string) => request<T>("/users/" + id, { method: "DELETE" }),');
    expect(contents).toContain("export const ordersApi = {");
    expect(contents).toContain('new URLSearchParams(query as any).toString()');
  });

  it("produces output that typechecks against the real project", async () => {
    const cwd = await makeTmpDir();
    const { root } = await generateProject(
      { projectName: ".", framework: "hono", language: "typescript", db: "none", routes: [], copyEnv: false },
      cwd
    );
    await addRoute("users", root);
    await addCrudMethods("users", root);
    await runGenerateClient(root, "ts");

    const install = Bun.spawn(["bun", "install"], { cwd: root, stdout: "pipe", stderr: "pipe" });
    await install.exited;

    const tsc = Bun.spawn(["bun", "run", "typecheck"], { cwd: root, stdout: "pipe", stderr: "pipe" });
    const exitCode = await tsc.exited;
    const stderr = await new Response(tsc.stderr).text();
    const stdout = await new Response(tsc.stdout).text();
    expect(exitCode, `typecheck failed:\n${stdout}\n${stderr}`).toBe(0);
  }, 30000);

  it("exits cleanly without writing a file when no endpoint has any methods yet", async () => {
    const cwd = await makeTmpDir();
    const { root } = await generateProject(
      { projectName: ".", framework: "hono", language: "typescript", db: "none", routes: [], copyEnv: false },
      cwd
    );
    await addRoute("users", root); // blank — no methods

    const { stdout } = await runGenerateClient(root, "ts");
    expect(stdout).toContain("nothing to generate");
    expect(await exists(join(root, "client/api.ts"))).toBe(false);
  });
});

describe("generate-client script (JavaScript)", () => {
  it("writes an untyped client — same shape, no type annotations or schema imports", async () => {
    const cwd = await makeTmpDir();
    const { root } = await generateProject(
      { projectName: ".", framework: "express", language: "javascript", db: "none", routes: [], copyEnv: false },
      cwd
    );
    await addRoute("users", root);
    await addCrudMethods("users", root);

    await runGenerateClient(root, "js");

    const contents = await readFile(join(root, "client/api.js"), "utf-8");
    expect(contents).not.toContain("z.infer");
    expect(contents).not.toContain("import type");
    expect(contents).toContain("export const usersApi = {");
    expect(contents).toContain('create: (body) => request("/users", { method: "POST", body: JSON.stringify(body) }),');
    expect(contents).toContain('getById: (id) => request("/users/" + id),');
  });
});
